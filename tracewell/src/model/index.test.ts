describe('model public API', () => {
  it('exports exactly the planned runtime values', () => {
    expect(Object.keys(model).sort()).toEqual(
      [
        'APP_NAME',
        'AUDIT_GENESIS_PREFIX',
        'BATCH_ROWS',
        'EXCEL_MAX_CELL_CHARS',
        'EXCEL_MAX_DATA_ROWS',
        'EngineError',
        'MIN_REASON_LENGTH',
        'PREVIEW_MAX_BYTES',
        'ROW_WINDOW_MAX',
        'canonicalCell',
        'canonicalJson',
        'canonicalNumber',
        'detection',
        'isBelowDetectionLimit',
        'isDateCell',
        'isDateTimeCell',
        'isGeometryCell',
        'rawToText',
        'schemas',
        'userDetection',
        'utf8',
      ].sort(),
    );
  });

  it('has the planned constant values', () => {
    expect(model.APP_NAME).toBe('Tracewell');
    expect(model.EXCEL_MAX_DATA_ROWS).toBe(1_048_575);
    expect(model.EXCEL_MAX_CELL_CHARS).toBe(32_767);
    expect(model.PREVIEW_MAX_BYTES).toBe(1_048_576);
    expect(model.ROW_WINDOW_MAX).toBe(1000);
    expect(model.BATCH_ROWS).toBe(65_536);
    expect(model.MIN_REASON_LENGTH).toBe(3);
    expect(model.AUDIT_GENESIS_PREFIX).toBe('tracewell-audit-v1:');
  });

  it('exposes the planned signatures', () => {
    expectTypeOf(model.canonicalNumber).toEqualTypeOf<(n: number) => string>();
    expectTypeOf(model.canonicalJson).toEqualTypeOf<(v: JsonValue) => string>();
    expectTypeOf(model.canonicalCell).toEqualTypeOf<(v: CellValue) => string>();
    expectTypeOf(model.utf8).toEqualTypeOf<(s: string) => Uint8Array>();
    expectTypeOf(model.rawToText).toEqualTypeOf<(v: RawField) => string>();
    expectTypeOf(model.userDetection<string>).toEqualTypeOf<(value: string, seq: AuditSeq) => Detection<string>>();
    expectTypeOf(model.EngineError.from).toEqualTypeOf<(e: unknown) => model.EngineError>();
    expectTypeOf<ColumnPlan>().not.toHaveProperty('derivedFrom');
    expectTypeOf<Step>().toExtend<StepInput & { id: StepId; seq: AuditSeq }>();
  });

  it('exposes the planned detection, guard, error and schema types', () => {
    expectTypeOf(model.detection<string>).toEqualTypeOf<
      (
        value: string,
        confidence: Confidence,
        method: string,
        evidence: string,
        source?: 'detected' | 'default',
      ) => Detection<string>
    >();
    expectTypeOf(model.isDateCell).toEqualTypeOf<(v: unknown) => v is DateCell>();
    expectTypeOf(model.isDateTimeCell).toEqualTypeOf<(v: unknown) => v is DateTimeCell>();
    expectTypeOf(model.isGeometryCell).toEqualTypeOf<(v: unknown) => v is GeometryCell>();
    expectTypeOf(model.EngineError).constructorParameters.toEqualTypeOf<
      [code: ErrorCode, message: string, fix: string, detail?: JsonValue | undefined]
    >();
    expectTypeOf<model.EngineError['toData']>().toEqualTypeOf<() => EngineErrorData>();
    expectTypeOf(model.schemas).toEqualTypeOf<{
      auditEntry: z.ZodType<AuditEntry>;
      rulePack: z.ZodType<RulePack>;
      stepInput: z.ZodType<StepInput>;
      decision: z.ZodType<Decision>;
      projectManifest: z.ZodType<ProjectManifest>;
      exportManifest: z.ZodType<ExportManifest>;
      unitRegistry: z.ZodType<{ version: string; units: UnitDef[] }>;
      mappingTemplate: z.ZodType<MappingTemplate>;
    }>();
  });
});
